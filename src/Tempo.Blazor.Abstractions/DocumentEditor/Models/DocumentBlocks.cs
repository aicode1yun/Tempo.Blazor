    /// <summary>Stable list style identifier.</summary>
    public string Id { get; set; } = Guid.NewGuid().ToString("N");

    /// <summary>User-facing style name.</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>Referenced concrete numbering identifier.</summary>
    public string NumberingId { get; set; } = string.Empty;

    /// <summary>Whether the style should be shown in quick style pickers.</summary>
    public bool IsQuickStyle { get; set; }
}

