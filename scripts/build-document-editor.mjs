#!/usr/bin/env node
// Builds the headless document layout bundle embedded in Tempo.Blazor.DocumentFormats.
//
// `npm run build:document-editor`            — (re)writes the bundle artifact.
// `node scripts/build-document-editor.mjs --check` — drift gate: fails (exit 1) when the
//     committed artifact no longer matches a fresh esbuild of the .mjs sources. Wired
//     into the Tempo.Blazor.DocumentFormats MSBuild pre-build and the Node test lane so
//     a stale embedded bundle can never ship silently.
//
// The bundle packages the canvas layout chain (layout-snapshot-export → display-list →
// pagination → line breaker/paragraph engine/font metrics) as a single ESM file;
// interop.mjs and the paint/canvas modules are browser-only and are not reachable from
// the entry. Run this after every change to the bundled .mjs sources.
import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const BUNDLE_ENTRY = 'src/Tempo.Blazor.DocumentEditor/wwwroot/js/document-editor-canvas/headless-layout-entry.mjs';
export const BUNDLE_OUTFILE = 'src/Tempo.Blazor.DocumentFormats/HeadlessLayout/tempo-document-headless-layout.bundle.mjs';

const BANNER = `// Generated by scripts/build-document-editor.mjs — DO NOT EDIT.
// Headless document layout bundle (embedded resource of Tempo.Blazor.DocumentFormats).
// Source of truth: ${BUNDLE_ENTRY} and its imports.
// Rebuild: npm run build:document-editor`;

export function normalizeLineEndings(text) {
    return String(text).replace(/\r\n/g, '\n');
}

// Bundles the headless entry in-memory and returns the artifact text.
export async function buildHeadlessLayoutBundleText() {
    const result = await esbuild.build({
        entryPoints: [path.join(repoRoot, BUNDLE_ENTRY)],
        outfile: path.join(repoRoot, BUNDLE_OUTFILE),
        bundle: true,
        format: 'esm',
        platform: 'neutral',
        mainFields: ['module', 'main'],
        target: ['es2022'],
        sourcemap: false,
        legalComments: 'none',
        banner: { js: BANNER },
        write: false,
    });

    return normalizeLineEndings(result.outputFiles[0].text);
}

export async function checkBundleDrift() {
    const outfilePath = path.join(repoRoot, BUNDLE_OUTFILE);
    if (!existsSync(outfilePath)) {
        return { upToDate: false, reason: `missing artifact: ${BUNDLE_OUTFILE}` };
    }

    const fresh = await buildHeadlessLayoutBundleText();
    const committed = normalizeLineEndings(readFileSync(outfilePath, 'utf8'));
    return committed === fresh
        ? { upToDate: true }
        : { upToDate: false, reason: `stale artifact: ${BUNDLE_OUTFILE} does not match the .mjs sources` };
}

async function main() {
    if (process.argv.includes('--check')) {
        const drift = await checkBundleDrift();
        if (!drift.upToDate) {
            console.error(`headless layout bundle drift: ${drift.reason}`);
            console.error('Run `npm run build:document-editor` and commit the regenerated artifact.');
            process.exit(1);
        }

        console.log('headless layout bundle is up to date.');
        return;
    }

    const text = await buildHeadlessLayoutBundleText();
    const outfilePath = path.join(repoRoot, BUNDLE_OUTFILE);
    mkdirSync(path.dirname(outfilePath), { recursive: true });
    writeFileSync(outfilePath, text, 'utf8');
    console.log(`built ${BUNDLE_OUTFILE} (${(text.length / 1024).toFixed(1)} KiB)`);
}

// Run main only when invoked as a CLI (the test lane imports the functions instead).
// Compare case-insensitively on Windows — a drive-letter case mismatch must not turn
// the CLI (and with it the --check drift gate) into a silent no-op.
function canonicalPath(value) {
    const resolved = path.resolve(value);
    return process.platform === 'win32' ? resolved.toLowerCase() : resolved;
}

const invokedDirectly = process.argv[1]
    && canonicalPath(process.argv[1]) === canonicalPath(fileURLToPath(import.meta.url));
if (invokedDirectly) {
    await main();
}
